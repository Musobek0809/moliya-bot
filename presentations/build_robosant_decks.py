LINE = RGBColor(0xC5, 0xD8, 0xEC)


def set_run(run, text, size=18, bold=False, color=INK, font="Calibri"):
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = font
    rPr = run._r.get_or_add_rPr()
    # East Asian / complex script fallback
    for tag in ("a:latin", "a:ea", "a:cs"):
        el = rPr.find("{http://schemas.openxmlformats.org/drawingml/2006/main}%s" % tag.split(":")[1])
        if el is None:
            el = etree.SubElement(
                rPr,
                "{http://schemas.openxmlformats.org/drawingml/2006/main}%s" % tag.split(":")[1],
            )
        el.set("typeface", font)


def add_text(shape, text, size=18, bold=False, color=INK, align=PP_ALIGN.LEFT, font="Calibri"):
    tf = shape.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    p.clear()
    run = p.add_run()
    set_run(run, text, size, bold, color, font)
    return tf


def add_para(tf, text, size=16, bold=False, color=INK, align=PP_ALIGN.LEFT, space_before=6, space_after=4):
    p = tf.add_paragraph()
    p.alignment = align
    p.space_before = Pt(space_before)
    p.space_after = Pt(space_after)
    run = p.add_run()
    set_run(run, text, size, bold, color)
    return p


def rect(slide, l, t, w, h, fill, line=None):
    s = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, l, t, w, h)
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(1)
    s.shadow.inherit = False
    return s


def pic(slide, name, l, t, width=None, height=None):
    path = IMG / name
    if not path.exists():
        return None
    kwargs = {}
    if width is not None:
        kwargs["width"] = width
    if height is not None:
        kwargs["height"] = height
    return slide.shapes.add_picture(str(path), l, t, **kwargs)


def round_rect(slide, l, t, w, h, fill, line=None):
    s = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, l, t, w, h)
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(1.25)
    # softer corners
    try:
        s.adjustments[0] = 0.08
    except Exception:
        pass
    s.shadow.inherit = False
    return s


def tb(slide, l, t, w, h, text, size=18, bold=False, color=INK, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(l, t, w, h)
    box.text_frame.word_wrap = True
    box.text_frame.auto_size = None
    try:
        box.text_frame.paragraphs[0].alignment = align
    except Exception:
        pass
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    set_run(run, text, size, bold, color)
    return box


def chrome(slide, footer, page, total, hotel=False):
    rect(slide, 0, 0, W, H, WHITE)
    rect(slide, 0, 0, W, Inches(0.08), BLUE)
    rect(slide, 0, Inches(7.28), W, Inches(0.22), NAVY)
    tb(slide, Inches(0.4), Inches(7.28), Inches(10), Inches(0.22), footer, 10, False, WHITE, PP_ALIGN.LEFT)
    tb(
        slide,
        Inches(11.2),
        Inches(7.28),
        Inches(1.7),
        Inches(0.22),
        f"{page} / {total}",
        10,
        False,
        WHITE,
        PP_ALIGN.RIGHT,
    )


def header(slide, kicker, title, subtitle=None):
    tb(slide, Inches(0.45), Inches(0.22), Inches(12.4), Inches(0.28), kicker, 12, True, BLUE)
    tb(slide, Inches(0.45), Inches(0.46), Inches(12.4), Inches(0.48), title, 28, True, NAVY)
    if subtitle:
        tb(slide, Inches(0.45), Inches(0.92), Inches(12.4), Inches(0.36), subtitle, 14, False, MUTED)


def card(slide, l, t, w, h, title, body, title_size=16, body_size=13):
    sh = round_rect(slide, l, t, w, h, CARD, LINE)
    tb(slide, l + Inches(0.18), t + Inches(0.14), w - Inches(0.36), Inches(0.4), title, title_size, True, NAVY)
    box = slide.shapes.add_textbox(l + Inches(0.18), t + Inches(0.52), w - Inches(0.36), h - Inches(0.64))
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.LEFT
    run = p.add_run()
    set_run(run, body, body_size, False, INK)
    return sh


def bullets(slide, l, t, w, h, items, size=15):
    box = slide.shapes.add_textbox(l, t, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = PP_ALIGN.LEFT
        p.space_after = Pt(8)
        run = p.add_run()
        set_run(run, "▸  " + item, size, False, INK)
    return box


def kpi_row(slide, items, top=Inches(1.45)):
    n = len(items)
    gap = Inches(0.18)
    left = Inches(0.45)
    usable = W - Inches(0.9) - gap * (n - 1)
    cw = usable / n
    for i, (num, label) in enumerate(items):
        x = left + i * (cw + gap)
        round_rect(slide, x, top, cw, Inches(1.15), SKY, LINE)
        tb(slide, x, top + Inches(0.12), cw, Inches(0.5), num, 22, True, NAVY, PP_ALIGN.CENTER)
        tb(slide, x + Inches(0.08), top + Inches(0.58), cw - Inches(0.16), Inches(0.48), label, 12, False, MUTED, PP_ALIGN.CENTER)


